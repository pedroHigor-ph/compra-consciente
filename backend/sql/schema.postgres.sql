-- Compra Consciente schema for PostgreSQL (including Neon).
-- Apply to a new/empty PostgreSQL database. This file does not drop tables.

CREATE TABLE IF NOT EXISTS categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_categories PRIMARY KEY (id),
    CONSTRAINT uq_categories_name UNIQUE (name)
);

CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    category_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    description TEXT,
    price NUMERIC(10, 2) NOT NULL,
    quantity NUMERIC(10, 3) NOT NULL,
    unit VARCHAR(2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id)
        REFERENCES categories(id) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT chk_products_unit CHECK (unit IN ('g', 'kg', 'ml', 'L', 'un')),
    CONSTRAINT chk_products_price_positive CHECK (price > 0),
    CONSTRAINT chk_products_quantity_positive CHECK (quantity > 0)
);

CREATE INDEX IF NOT EXISTS idx_products_category_id ON products(category_id);
CREATE INDEX IF NOT EXISTS idx_products_name ON products(name);

CREATE TABLE IF NOT EXISTS educational_contents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    title VARCHAR(150) NOT NULL,
    slug VARCHAR(150) NOT NULL,
    summary VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    category VARCHAR(20) NOT NULL,
    published BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_educational_contents PRIMARY KEY (id),
    CONSTRAINT uq_educational_contents_slug UNIQUE (slug),
    CONSTRAINT chk_educational_contents_category CHECK (
        category IN ('consumo', 'sustentabilidade', 'planejamento',
                     'desperdicio', 'educacao', 'outros')
    )
);

CREATE INDEX IF NOT EXISTS idx_educational_contents_category
    ON educational_contents(category);
CREATE INDEX IF NOT EXISTS idx_educational_contents_published
    ON educational_contents(published);

CREATE TABLE IF NOT EXISTS feedbacks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    rating SMALLINT NOT NULL,
    comment TEXT,
    activity_context VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_feedbacks PRIMARY KEY (id),
    CONSTRAINT chk_feedbacks_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT chk_feedbacks_activity_context CHECK (
        activity_context IN ('comparador', 'economia', 'aprenda',
                             'catalogo', 'oficina', 'outros')
    )
);

CREATE INDEX IF NOT EXISTS idx_feedbacks_created_at ON feedbacks(created_at);
CREATE INDEX IF NOT EXISTS idx_feedbacks_context ON feedbacks(activity_context);

CREATE TABLE IF NOT EXISTS comparison_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    number_of_products SMALLINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_comparison_events PRIMARY KEY (id),
    CONSTRAINT chk_comparison_events_number_of_products
        CHECK (number_of_products BETWEEN 2 AND 5)
);

CREATE INDEX IF NOT EXISTS idx_comparison_events_created_at
    ON comparison_events(created_at);

-- Reproduce MySQL's ON UPDATE CURRENT_TIMESTAMP behavior in PostgreSQL.
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_products_updated_at ON products;
CREATE TRIGGER trg_products_updated_at
    BEFORE UPDATE ON products
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

DROP TRIGGER IF EXISTS trg_educational_contents_updated_at
    ON educational_contents;
CREATE TRIGGER trg_educational_contents_updated_at
    BEFORE UPDATE ON educational_contents
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
